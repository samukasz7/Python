numero1 = float(input('Digite o primeiro numero: '))
numero2 = float(input('Digite o segundo numero: '))
numero3 = float(input('Digite o tercerio numero: '))

if numero1 > numero2 + numero3:
    print('O primeiro numero é maior que a soma do segundo e terceiro numero juntos')
else:
    print('O primeiro numero é menor que a soma do segundo e terceiro numero juntos')